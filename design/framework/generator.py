"""
Generator: Task generation by graph traversal.

The core insight: tasks are generated by walking the entity graph.
The generator uses the SAME tools the agent will use. If the generator
can solve it, the agent can solve it (solvability by construction).

Implements:
- generate_graph_tasks(): THE MAIN FUNCTION — traversal-based generation
- compute_gated_depth(): BFS through gated graph
- compute_reachable_nodes(): BFS from entry point
- verify_solvable(): oracle simulation (redundant for graph-generated tasks)
- compose_blueprints(): cartesian product composition engine (legacy)
"""

from __future__ import annotations

import itertools
import random
from collections import deque
from dataclasses import dataclass, field
from typing import Any, Optional

from design.framework.gates import (
    ActorGate,
    CompoundGate,
    Gate,
    GatedRelationship,
    InformationGate,
    PropertyGate,
)
from design.framework.tasks import (
    GoalPredicate,
    PerturbationSpace,
    PerturbationSpec,
    TaskAtom,
    TaskAtomType,
    TaskBlueprint,
)
from design.framework.world import WorldSchema


# ══════════════════════════════════════════════════════════════════════
# GRAPH ANALYSIS
# ══════════════════════════════════════════════════════════════════════


def compute_reachable_nodes(
    schema: WorldSchema,
    gated_relationships: list[GatedRelationship],
    entry_entity: str,
    field_states: Optional[dict[tuple[str, str], Any]] = None,
) -> set[str]:
    """BFS from entry entity through the relationship graph.

    Respects gate conditions: a gated edge is only traversable if
    the gate condition is satisfied by the current field_states.

    Args:
        schema: world schema
        gated_relationships: edges with gate conditions
        entry_entity: starting entity type name
        field_states: current (entity, field) -> value mapping.
            If None, uses normal_value for all fields (everything open).

    Returns:
        Set of reachable entity type names.
    """
    if field_states is None:
        field_states = _default_field_states(schema)

    # Build adjacency: entity -> [(target_entity, gate_or_none)]
    adjacency: dict[str, list[tuple[str, Optional[Gate]]]] = {}
    for entity in schema.entities:
        adjacency[entity.name] = []

    # Ungated relationships
    gated_from = {
        (gr.relationship.from_entity, gr.relationship.to_entity)
        for gr in gated_relationships
    }
    for rel in schema.relationships:
        key = (rel.from_entity, rel.to_entity)
        if key not in gated_from:
            adjacency.setdefault(rel.from_entity, []).append(
                (rel.to_entity, None)
            )
            adjacency.setdefault(rel.to_entity, []).append(
                (rel.from_entity, None)
            )

    # Gated relationships
    for gr in gated_relationships:
        adjacency.setdefault(gr.relationship.from_entity, []).append(
            (gr.relationship.to_entity, gr.gate)
        )
        # Reverse direction is ungated (you can always go back)
        adjacency.setdefault(gr.relationship.to_entity, []).append(
            (gr.relationship.from_entity, None)
        )

    # BFS
    reachable = {entry_entity}
    queue = deque([entry_entity])

    while queue:
        current = queue.popleft()
        for target, gate in adjacency.get(current, []):
            if target in reachable:
                continue
            if gate is not None and not _gate_satisfied(gate, field_states):
                continue
            reachable.add(target)
            queue.append(target)

    return reachable


def compute_gated_depth(
    schema: WorldSchema,
    gated_relationships: list[GatedRelationship],
    entry_entity: str,
) -> int:
    """Compute the depth of the gated graph from an entry point.

    Depth = number of sequential gates that must be opened to reach
    the deepest node. This determines task difficulty.

    A depth of 0 means all nodes are directly reachable.
    A depth of N means N gates must be opened in sequence.
    """
    # Build adjacency with gate costs
    adjacency: dict[str, list[tuple[str, int]]] = {}
    for entity in schema.entities:
        adjacency[entity.name] = []

    gated_from = {
        (gr.relationship.from_entity, gr.relationship.to_entity)
        for gr in gated_relationships
    }
    for rel in schema.relationships:
        key = (rel.from_entity, rel.to_entity)
        if key not in gated_from:
            adjacency.setdefault(rel.from_entity, []).append(
                (rel.to_entity, 0)
            )
            adjacency.setdefault(rel.to_entity, []).append(
                (rel.from_entity, 0)
            )

    for gr in gated_relationships:
        adjacency.setdefault(gr.relationship.from_entity, []).append(
            (gr.relationship.to_entity, 1)
        )
        adjacency.setdefault(gr.relationship.to_entity, []).append(
            (gr.relationship.from_entity, 0)
        )

    # BFS finding minimum gate cost to reach each node (Dijkstra-like).
    # Depth = max over all nodes of (min gates to reach that node).
    depths: dict[str, int] = {entry_entity: 0}
    queue = deque([entry_entity])

    while queue:
        current = queue.popleft()
        for target, cost in adjacency.get(current, []):
            new_depth = depths[current] + cost
            if target not in depths or new_depth < depths[target]:
                depths[target] = new_depth
                queue.append(target)

    return max(depths.values()) if depths else 0


# ══════════════════════════════════════════════════════════════════════
# GRAPH-TRAVERSAL TASK GENERATION
# ══════════════════════════════════════════════════════════════════════


def generate_graph_tasks(
    schema: WorldSchema,
    gated_relationships: list[GatedRelationship],
    space: PerturbationSpace,
    entities: list[dict[str, Any]],
    entity_id_field: str,
    entry_entity: str,
    min_faults: int = 1,
    max_faults: int = 4,
    max_total_tasks: Optional[int] = None,
    seed: int = 42,
) -> list[TaskBlueprint]:
    """Generate tasks by walking the entity graph.

    Tasks are correct by construction: every perturbation is on a
    reachable entity, gate perturbations are included as prerequisites,
    and the solution trace follows the graph structure.

    Algorithm:
    1. Compute entity depths from entry point via BFS
    2. Classify each perturbation group as gate or content, with depth
    3. For each target depth (0 to max_graph_depth):
       - Mandatory: all gate groups at depths < target_depth
         (the agent MUST fix these to reach deeper entities)
       - Optional: content groups at depths 0..target_depth
         + gate groups at exactly target_depth (treated as content)
    4. Cartesian product over mandatory gate variants × optional choices
    5. Filter by min/max faults, sample if over budget
    6. Build TaskBlueprints with depth-ordered atoms (= solution trace)

    Solvability proof (by induction on depth):
      At depth 0: entry entity is always reachable.
      At depth D: all gates at depths 0..D-1 are mandatory (included in
      the task). The oracle fixes them in order, opening each gate.
      Content perturbations at depth D are then reachable. QED.
    """
    rng = random.Random(seed)

    # 1. Compute entity depths
    entity_depths = _compute_entity_depths(
        schema, gated_relationships, entry_entity
    )
    max_graph_depth = max(entity_depths.values()) if entity_depths else 0

    # 2. Identify gate fields: set of (entity_name, field_name)
    gate_field_set = _extract_all_gate_fields(gated_relationships)

    # 3. Classify groups by depth and role (gate vs content)
    gate_groups_by_depth: dict[int, list] = {}
    content_groups_by_depth: dict[int, list] = {}

    for group in space.groups:
        if not group.perturbations:
            continue
        # Group depth = depth of the entity its perturbations target
        first_p = group.perturbations[0]
        depth = entity_depths.get(first_p.entity, 0)
        is_gate = (first_p.entity, first_p.field) in gate_field_set

        if is_gate:
            gate_groups_by_depth.setdefault(depth, []).append(group)
        else:
            content_groups_by_depth.setdefault(depth, []).append(group)

    # 4. Generate tasks: for each entity × target_depth
    blueprints: list[TaskBlueprint] = []

    for entity in entities:
        for target_depth in range(max_graph_depth + 1):
            _generate_at_depth(
                target_depth=target_depth,
                entity=entity,
                entity_id_field=entity_id_field,
                entity_depths=entity_depths,
                gate_field_set=gate_field_set,
                gate_groups_by_depth=gate_groups_by_depth,
                content_groups_by_depth=content_groups_by_depth,
                min_faults=min_faults,
                max_faults=max_faults,
                blueprints=blueprints,
            )

    # 5. Sample if budget exceeded
    if max_total_tasks and len(blueprints) > max_total_tasks:
        blueprints = rng.sample(blueprints, max_total_tasks)

    return blueprints


def _generate_at_depth(
    *,
    target_depth: int,
    entity: dict,
    entity_id_field: str,
    entity_depths: dict[str, int],
    gate_field_set: set[tuple[str, str]],
    gate_groups_by_depth: dict[int, list],
    content_groups_by_depth: dict[int, list],
    min_faults: int,
    max_faults: int,
    blueprints: list[TaskBlueprint],
) -> None:
    """Generate all valid tasks for one entity at one target depth."""

    # Mandatory: all gate groups at depths < target_depth
    mandatory_gate_groups = []
    for d in range(target_depth):
        for g in gate_groups_by_depth.get(d, []):
            mandatory_gate_groups.append(g)

    # Optional: content groups at depths 0..target_depth
    # + gate groups at target_depth (as optional, they gate deeper
    #   levels but fixing them is a valid content task at this depth)
    optional_groups = []
    for d in range(target_depth + 1):
        for g in content_groups_by_depth.get(d, []):
            optional_groups.append(g)
    for g in gate_groups_by_depth.get(target_depth, []):
        optional_groups.append(g)

    # Build mandatory gate variants (cartesian over mandatory groups)
    # Each mandatory group must contribute exactly 1 perturbation.
    mandatory_variants: list[list[PerturbationSpec]] = [[]]
    for gate_group in mandatory_gate_groups:
        eligible = [
            p for p in gate_group.perturbations
            if _check_predicate(p, entity)
        ]
        if not eligible:
            # Can't satisfy this gate for this entity → no tasks at this depth
            return
        new_variants = []
        for variant in mandatory_variants:
            for p in eligible:
                new_variants.append(variant + [p])
        mandatory_variants = new_variants

    # Build optional choices (0 or 1 per group)
    optional_choices: list[list[Optional[PerturbationSpec]]] = []
    for group in optional_groups:
        eligible = [
            p for p in group.perturbations
            if _check_predicate(p, entity)
        ]
        optional_choices.append(eligible + [None])

    # Cartesian product: mandatory × optional
    for mandatory in mandatory_variants:
        if not optional_choices:
            # Only mandatory perturbations
            if len(mandatory) < min_faults or len(mandatory) > max_faults:
                continue
            bp = _build_traversal_blueprint(
                mandatory, entity, entity_id_field,
                entity_depths, gate_field_set,
            )
            blueprints.append(bp)
            continue

        for optional_combo in itertools.product(*optional_choices):
            active_optional = [p for p in optional_combo if p is not None]
            active = list(mandatory) + active_optional

            if len(active) < min_faults or len(active) > max_faults:
                continue

            bp = _build_traversal_blueprint(
                active, entity, entity_id_field,
                entity_depths, gate_field_set,
            )
            blueprints.append(bp)


def _build_traversal_blueprint(
    perturbations: list[PerturbationSpec],
    entity: dict,
    entity_id_field: str,
    entity_depths: dict[str, int],
    gate_field_set: set[tuple[str, str]],
) -> TaskBlueprint:
    """Build a TaskBlueprint with depth-ordered atoms (= solution trace).

    Atoms are ordered by (depth, is_content) so gates come first
    within each depth level. This ordering IS the solution: fix gate
    at depth 0, then content at depth 0, then gate at depth 1, etc.
    """
    # Sort: by depth ascending, then gates before content within depth
    def sort_key(p: PerturbationSpec) -> tuple[int, int]:
        depth = entity_depths.get(p.entity, 0)
        is_gate = (p.entity, p.field) in gate_field_set
        return (depth, 0 if is_gate else 1)

    sorted_perturbs = sorted(perturbations, key=sort_key)

    atoms = []
    for p in sorted_perturbs:
        depth = entity_depths.get(p.entity, 0)
        atoms.append(TaskAtom(
            atom_type=TaskAtomType.PERTURBATION,
            entity=p.entity,
            description=p.description,
            field=p.field,
            broken_value=p.broken_value,
            fixed_value=p.check_value if p.check_value is not None else None,
            depth=depth,
            goal=GoalPredicate(
                entity=p.entity,
                field=p.check_field or p.field,
                expected_value=p.check_value,
                description=p.fixed_description,
            ),
        ))

    goals = [a.goal for a in atoms if a.goal is not None]
    eid = entity.get(entity_id_field, "unknown")
    pnames = "|".join(p.name for p in sorted_perturbs)
    goal_desc = " and ".join(p.fixed_description for p in sorted_perturbs)

    return TaskBlueprint(
        task_id=f"{pnames}_{eid}",
        entity=entity,
        perturbations=sorted_perturbs,
        goal_description=goal_desc,
        difficulty=min(len(sorted_perturbs), 5),
        atoms=atoms,
        goals=goals,
    )


def _extract_all_gate_fields(
    gated_relationships: list[GatedRelationship],
) -> set[tuple[str, str]]:
    """Extract all (entity, field) pairs that are gate conditions."""
    gate_fields: set[tuple[str, str]] = set()
    for gr in gated_relationships:
        _collect_gate_fields(gr.gate, gate_fields)
    return gate_fields


def _collect_gate_fields(gate: Gate, out: set[tuple[str, str]]) -> None:
    """Recursively collect gate field references."""
    if isinstance(gate, PropertyGate):
        out.add((gate.entity, gate.field))
    elif isinstance(gate, ActorGate):
        out.add((gate.actor, gate.field))
    elif isinstance(gate, CompoundGate):
        for c in gate.conditions:
            _collect_gate_fields(c, out)


# ══════════════════════════════════════════════════════════════════════
# SOLVABILITY VERIFICATION
# ══════════════════════════════════════════════════════════════════════


def verify_solvable(
    schema: WorldSchema,
    gated_relationships: list[GatedRelationship],
    blueprint: TaskBlueprint,
    entry_entity: str,
    max_steps: int = 100,
) -> bool:
    """Verify a task is solvable by simulating an oracle agent.

    The oracle has full visibility (ignores projections) and knows
    the optimal operation order. It simulates fixing perturbations
    and checks whether all goals become reachable.

    This is the Level 2 solvability guarantee (simulation).
    Level 1 (construction) is inherent in traversal-generated tasks.
    Level 3 (constraint) is done by static analysis in verify.py.
    """
    # Start with all perturbations broken
    field_states = _default_field_states(schema)
    for p in blueprint.perturbations:
        field_states[(p.entity, p.field)] = p.broken_value

    # Iteratively fix reachable perturbations
    remaining = list(blueprint.perturbations)
    steps = 0

    while remaining and steps < max_steps:
        reachable = compute_reachable_nodes(
            schema, gated_relationships, entry_entity, field_states
        )

        # Find perturbations on reachable entities
        fixable = [p for p in remaining if p.entity in reachable]
        if not fixable:
            return False  # stuck — no reachable perturbation to fix

        # Fix the first reachable perturbation (simulates oracle)
        p = fixable[0]
        field_spec = _get_field_spec(schema, p.entity, p.field)
        if field_spec and field_spec.normal_value is not None:
            field_states[(p.entity, p.field)] = field_spec.normal_value
        elif p.check_value is not None:
            field_states[(p.entity, p.field)] = p.check_value
        else:
            # Can't determine fixed value — remove anyway
            pass

        remaining.remove(p)
        steps += 1

    return len(remaining) == 0


# ══════════════════════════════════════════════════════════════════════
# COMPOSITION ENGINE
# ══════════════════════════════════════════════════════════════════════


def compose_blueprints(
    space: PerturbationSpace,
    entities: list[dict[str, Any]],
    entity_id_field: str,
    seed: int = 42,
) -> list[TaskBlueprint]:
    """Generate all valid TaskBlueprints from a PerturbationSpace + entities.

    This is the format-agnostic composition engine. It computes the
    cartesian product over groups for each entity, filters by
    min/max perturbations, samples if needed, and returns blueprints.
    """
    rng = random.Random(seed)
    blueprints: list[TaskBlueprint] = []

    for entity in entities:
        # Build per-group choices (each perturbation or None)
        group_choices: list[list[Optional[PerturbationSpec]]] = []
        for group in space.groups:
            eligible = [
                p for p in group.perturbations
                if _check_predicate(p, entity)
            ]
            group_choices.append(eligible + [None])

        # Cartesian product
        for combo in itertools.product(*group_choices):
            active = [p for p in combo if p is not None]
            if len(active) < space.min_perturbations:
                continue
            if len(active) > space.max_perturbations:
                continue

            # Check required groups
            if space.required_groups:
                active_group_names = set()
                for p in active:
                    for g in space.groups:
                        if p in g.perturbations:
                            active_group_names.add(g.name)
                if not all(
                    rg in active_group_names for rg in space.required_groups
                ):
                    continue

            eid = entity.get(entity_id_field, "unknown")
            pnames = "|".join(p.name for p in active)
            goal = " and ".join(p.fixed_description for p in active)
            difficulty = min(len(active), 5)

            blueprints.append(TaskBlueprint(
                task_id=f"{pnames}_{eid}",
                entity=entity,
                perturbations=active,
                goal_description=goal,
                difficulty=difficulty,
            ))

    # Sample if budget exceeded
    if space.max_total_tasks and len(blueprints) > space.max_total_tasks:
        blueprints = rng.sample(blueprints, space.max_total_tasks)

    return blueprints


