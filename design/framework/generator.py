# INTERNAL HELPERS
# ══════════════════════════════════════════════════════════════════════


def _default_field_states(schema: WorldSchema) -> dict[tuple[str, str], Any]:
    """Build default field states from schema (all normal values)."""
    states: dict[tuple[str, str], Any] = {}
    for entity in schema.entities:
        for f in entity.fields:
            if f.normal_value is not None:
                states[(entity.name, f.name)] = f.normal_value
    return states


def _get_field_spec(schema, entity_name, field_name):
    """Look up a FieldSpec by entity and field name."""
    for entity in schema.entities:
        if entity.name == entity_name:
            for f in entity.fields:
                if f.name == field_name:
                    return f
    return None


def _gate_satisfied(
    gate: Gate,
    field_states: dict[tuple[str, str], Any],
) -> bool:
    """Check if a gate condition is satisfied by current field states."""
    if isinstance(gate, PropertyGate):
        actual = field_states.get((gate.entity, gate.field))
        return actual == gate.required_value

    if isinstance(gate, ActorGate):
        actual = field_states.get((gate.actor, gate.field))
        return actual == gate.required_value

    if isinstance(gate, InformationGate):
        # Information gates are satisfied if the source field has a value
        actual = field_states.get((gate.source_entity, gate.source_field))
        return actual is not None

    if isinstance(gate, CompoundGate):
        return all(_gate_satisfied(c, field_states) for c in gate.conditions)

    return True  # unknown gate type → treat as open


def _compute_entity_depths(
    schema: WorldSchema,
    gated_relationships: list[GatedRelationship],
    entry_entity: str,
) -> dict[str, int]:
    """Compute the gate-depth of each entity from the entry point."""
    adjacency: dict[str, list[tuple[str, int]]] = {}
    for entity in schema.entities:
        adjacency[entity.name] = []

    gated_from = {
        (gr.relationship.from_entity, gr.relationship.to_entity)
        for gr in gated_relationships
    }
    for rel in schema.relationships:
        key = (rel.from_entity, rel.to_entity)
        if key not in gated_from:
            adjacency.setdefault(rel.from_entity, []).append(
                (rel.to_entity, 0)
            )
            adjacency.setdefault(rel.to_entity, []).append(
                (rel.from_entity, 0)
            )

    for gr in gated_relationships:
        adjacency.setdefault(gr.relationship.from_entity, []).append(
            (gr.relationship.to_entity, 1)
        )
        adjacency.setdefault(gr.relationship.to_entity, []).append(
            (gr.relationship.from_entity, 0)
        )

    depths: dict[str, int] = {entry_entity: 0}
    queue = deque([entry_entity])

    while queue:
        current = queue.popleft()
        for target, cost in adjacency.get(current, []):
            new_depth = depths[current] + cost
            if target not in depths or new_depth < depths[target]:
                depths[target] = new_depth
                queue.append(target)

    return depths


def _check_predicate(p: PerturbationSpec, entity: dict) -> bool:
    """Check if a perturbation applies to an entity."""
    if p.requires_field:
        return bool(entity.get(p.requires_field))
    if p.requires_ne:
        field_name, value = p.requires_ne
        return entity.get(field_name) != value
    return True
